const fs = require('node:fs'); const vm = require('node:vm'); const assert = require('node:assert/strict'); const path = require('node:path');
const sandbox = vm.createContext({});
for (const name of ['marked.umd', 'markdown']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../Resources/' + name + '.js'), 'utf8'), sandbox);
const md = sandbox.MojianMarkdown;
const input = '# 示例\n\n==水面：暗==\n\n`==原样==`\n\n```html\n<img src="private.png">\n==代码==\n```\n\n<img src="https://example.com/a(1).png" alt="示例" style="zoom:50%;" />\n\n![本地](assets/a.png)\n';
assert.match(md.render(input), /<mark>水面：暗<\/mark>/);
assert.match(md.render(input), /<code>==原样==<\/code>/);
const out = md.prepare(input);
assert.match(out.body, /\*\*水面：暗\*\*/);
assert.match(out.body, /`==原样==`/);
assert.match(out.body, /```html\n<img src="private.png">\n==代码==\n```/);
assert.match(out.body, /!\[示例\]\(<https:\/\/example.com\/a\(1\).png>\)/);
assert.equal(out.highlights, 1); assert.equal(out.htmlImages, 1); assert.deepEqual(Array.from(out.localImages), ['assets/a.png']);
assert.equal(md.prepare('~~~\n==same==\n~~~\n').highlights, 0);
assert.equal(md.prepare('    ==same==\n').highlights, 0);
assert.equal(md.prepare('- item\n\n      ==code==\n').highlights, 0);
assert.match(md.prepare('- item\n\n      ==code==\n').body, /==code==/);
assert.match(md.prepare('**==嵌套==**').body, /嵌套/);
assert.equal(md.prepare('![引用][asset]\n\n[asset]: local.png\n').localImages[0], 'local.png');
assert.equal(md.frontmatter('---\ntypora-root-url: ./media\n---\n# 标题').root, './media');
assert.match(md.render('| 名称 | 值 |\n| --- | --- |\n| 水面 | 暗 |'), /<table>/);
assert.match(md.render('\\==普通文字=='), /==普通文字==/);
console.log('通过：高亮、嵌套格式、代码隔离、HTML 图片转换、引用图片、相对路径、表格、转义标记。');
const headings = '# SAR 基础\n\n## 散射机制\n\n## SAR 几何特征\n\n### 透视收缩\n\n### 叠掩\n\n## 星载 SAR\n\n### 条带\n\n# 第二章\n\n## 内容\n';
const numbered = md.numberHeadings(headings);
assert.equal(numbered, '# 1. SAR 基础\n\n## 1.1. 散射机制\n\n## 1.2. SAR 几何特征\n\n### 1.2.1. 透视收缩\n\n### 1.2.2. 叠掩\n\n## 1.3. 星载 SAR\n\n### 1.3.1. 条带\n\n# 2. 第二章\n\n## 2.1. 内容\n');
assert.equal(md.numberHeadings(numbered), numbered);
assert.equal(md.numberHeadings('## A\n#### B\n## C\n'), '## 1. A\n#### 1.1. B\n## 2. C\n');
assert.equal(md.numberHeadings('标题\n====\n\n子节\n----\n'), '# 1. 标题\n\n## 1.1. 子节\n');
assert.equal(md.numberHeadings('---\ntitle: Note\n---\n# Head\n\n```md\n# Example\n```\n\n    # Indented\n\n> # Quoted\n'), '---\ntitle: Note\n---\n# 1. Head\n\n```md\n# Example\n```\n\n    # Indented\n\n> # Quoted\n');
assert.equal(md.numberHeadings('# 1.SAR 基础\n## 1.1.散射机制\n'), '# 1. SAR 基础\n## 1.1. 散射机制\n');
assert.equal(md.numberHeadings('# No newline'), '# 1. No newline');
console.log('通过：六级标题编号、换章重置、跳级标题、Setext、去重、代码与引用隔离、无末尾换行。');

assert.equal(md.numberHeadings("# A\n## B\n### C\n#### D\n##### E\n###### F\n"), "# 1. A\n## 1.1. B\n### 1.1.1. C\n#### 1.1.1.1. D\n##### 1.1.1.1.1. E\n###### 1.1.1.1.1.1. F\n");
const maskSource = '姓名：**\n\n******\n\n`****`\n\n```js\nkey="***"\n```';
const protectedMasks = md.protectPrivacyMasks(maskSource, [...maskSource.matchAll(/\*+/g)].map(m => [m.index, m[0].length]));
assert.match(md.render(protectedMasks), /姓名：\*\*/);
assert.doesNotMatch(md.render(protectedMasks), /<hr/);
assert.match(md.render(protectedMasks), /<code>\*\*\*\*<\/code>/);
console.log('通过：隐私星号在预览中按原字符显示，不触发分割线，代码中的星号保持原样。');

assert.match(md.render(protectedMasks), /key=&quot;\*\*\*&quot;/);
